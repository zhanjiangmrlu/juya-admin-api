from sqlalchemy import (
    JSON,
    BigInteger,
    Boolean,
    Column,
    Integer,
    LargeBinary,
    MetaData,
    String,
    Table,
    Text,
)

metadata = MetaData()
targets = Table(
    "pronunciation_target",
    metadata,
    Column("public_id", String(64), primary_key=True),
    Column("confirmed_text", Text, nullable=False),
    Column("reading_variant", String(255), nullable=False, default=""),
    Column("language", String(32), nullable=False, default="en"),
    Column("target_type", String(16), nullable=False, default="WORD"),
    Column("allow_synthesis", Boolean, nullable=False),
    Column("uploaded_target_id", String(64)),
    Column("uploaded_resource_version", String(64)),
    Column("status", String(32), nullable=False),
    Column("config_version", String(64), nullable=False),
    Column("confirmed_by", String(64), nullable=False),
    Column("confirmed_at", BigInteger, nullable=False),
    Column("created_at", BigInteger, nullable=False),
)
cache = Table(
    "pronunciation_cache",
    metadata,
    Column("cache_key", String(64), primary_key=True),
    Column("object_key", Text, nullable=False),
    Column("resource_version", String(64), nullable=False),
    Column("duration_ms", Integer, nullable=False),
    Column("created_at", BigInteger, nullable=False),
)
tasks = Table(
    "pronunciation_task",
    metadata,
    Column("public_id", String(64), primary_key=True),
    Column("cache_key", String(64), unique=True, nullable=False),
    Column("target_id", String(64), nullable=False),
    Column("config", JSON, nullable=False),
    Column("target_snapshot", JSON, nullable=False),
    Column("status", String(32), nullable=False),
    Column("attempt", Integer, nullable=False, default=0),
    Column("lease_token", String(64)),
    Column("lease_until", BigInteger, nullable=False, default=0),
    Column("next_retry_at", BigInteger, nullable=False, default=0),
    Column("audio", LargeBinary(length=16777215)),
    Column("object_key", Text),
    Column("request_id", String(128)),
    Column("error_code", String(128)),
    Column("outbox_pending", Boolean, nullable=False, default=True),
    Column("created_at", BigInteger, nullable=False),
)
budgets = Table(
    "budget_reservation",
    metadata,
    Column("period", String(64), primary_key=True),
    Column("character_limit", BigInteger, nullable=False),
    Column("cost_limit", BigInteger, nullable=False),
    Column("reserved_characters", BigInteger, nullable=False, default=0),
    Column("reserved_cost", BigInteger, nullable=False, default=0),
    Column("enabled", Boolean, nullable=False),
)
attempts = Table(
    "cloud_usage_attempt",
    metadata,
    Column("public_id", String(64), primary_key=True),
    Column("task_id", String(64), nullable=False),
    Column("attempt", Integer, nullable=False),
    Column("period", String(64), nullable=False),
    Column("estimated_characters", BigInteger, nullable=False),
    Column("estimated_cost", BigInteger, nullable=False),
    Column("actual_characters", BigInteger),
    Column("actual_cost", BigInteger),
    Column("price_version", String(64), nullable=False),
    Column("currency", String(8), nullable=False),
    Column("region", String(64), nullable=False),
    Column("provider_request_id", String(128)),
    Column("status", String(32), nullable=False),
    Column("error_code", String(128)),
    Column("created_at", BigInteger, nullable=False),
)
